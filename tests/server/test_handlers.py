    @pytest.mark.parametrize(
        ("task", "overrides"),
        [
            ("scf_single_point", {"k_distance": 0.2}),
            ("dos", {"k_distance": 0.2, "steps.dos.delta_e": 0.05}),
            ("band", {"k_path_distance": 0.05, "steps.bands.nbnd": 20}),
            ("relax", {"nstep": 123}),
            ("vc-relax", {"press": 10.0, "steps.vc-relax.nstep": 50}),
            (
                "phonon",
                {
                    "is_metal": "non_metal",
                    "q_distance": 0.4,
                    "steps.phonon_dos.dos_q_distance": 0.2,
                },
            ),
            (
                "relax-phonon",
                {
                    "is_metal": "non_metal",
                    "forc_conv_thr": 5e-5,
                    "steps.ph.tr2_ph": 1e-16,
                },
            ),
            (
                "vc-relax-phonon",
                {"is_metal": "non_metal", "press": 10.0, "asr": "simple"},
            ),
        ],
    )
    def test_the_manifest_records_the_request_as_submitted(
        self, silicon_fixture_table, silicon_cif, task, overrides
    ) -> None:
        """#176: goldilocks.json named no code, task, engine version,
        overrides or input structure. Each task's bundle now records the
        request it answers: the overrides exactly as the body sent them and
        the sha256 of the submitted structure_content."""
        document = ComputeRequestDocument(
            structure_content=silicon_cif,
            structure_name="Si.cif",
            hpc="scarf",
            task=task,
            overrides=overrides,
        )

        _summary, bundle_input = _handlers.run(document)

        files = {file["path"]: file["content"] for file in bundle_files(bundle_input)}
        manifest = strict_json(files["goldilocks.json"])
        content = silicon_cif.encode("utf-8")
        assert manifest["schema_version"] == 3
        assert manifest["request"] == {
            "code": "quantum_espresso",
            "task": task,
            "hpc": "scarf",
            "core_version": version("goldilocks-core"),
            "overrides": overrides,
            "structure": {
                "name": "Si.cif",
                "format": "cif",
                "sha256": hashlib.sha256(content).hexdigest(),
                "size_bytes": len(content),
            },
        }
        # #222: the manifest's steps and README.md list the inputs in the
        # order submit.sh runs them, not alphabetically.
        run_order = re.findall(r" -in (\S+)", files["submit.sh"].decode("utf-8"))
        assert [
            path for step in manifest["steps"] for path in step["files"]
        ] == run_order
        contents = re.findall(
            r"^- `([^`]+)`$", files["README.md"].decode("utf-8"), flags=re.M
        )
        assert contents[: len(run_order)] == run_order
        assert contents[len(run_order)] == "submit.sh"
        # #227: README.md says how to run the script, with the steps' output
        # files in the order submit.sh writes them and its resume command
        # exactly where submit.sh has one.
        script = files["submit.sh"].decode("utf-8")
        readme = files["README.md"].decode("utf-8")
        running = readme[readme.index("## Running it") :]
        assert re.findall(r"\(`(\S+\.out)`\)", running) == re.findall(
            r" > (\S+\.out)(?=\s|$)", script, flags=re.M
        )
        assert ("GOLDILOCKS_FROM_STEP" in running) == ("GOLDILOCKS_FROM_STEP" in script)


