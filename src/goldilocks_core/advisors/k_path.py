@dataclass(frozen=True, slots=True)
class PathVertex:
    """A vertex of the path: ``label``, its name as Setyawan and Curtarolo or
    ASE give it, in ASCII (``Gamma``, ``X_1``, ``A_1``), and ``k``, its crystal
    coordinates in the written cell's reciprocal vectors."""

    label: str
    k: tuple[float, float, float]


@dataclass(frozen=True, slots=True)
class PathBranch:
    """A continuous piece of the path: ``steps[i]`` equal steps lead from
    vertex i to vertex i + 1, so there is one fewer than vertices, each at
    least 1."""

    vertices: tuple[PathVertex, ...]
    steps: tuple[int, ...]


@dataclass(frozen=True, slots=True)
class KPathDecision:
    """The band path of the written cell (module docstring).

    ``k_path_distance`` is the largest spacing allowed between neighbouring
    points, in 1/Å with 2π included; ``n_kpoints`` the points the step runs,
    pw.x per spin channel on a bands step and matdyn.x on a dispersion step
    (whose path ``advisors/phonon.py``'s ``dispersion_path`` gives), the sum
    over the branches of their steps plus one.
    ``convention`` names the family of tables and ``lattice_type`` the table:
    Setyawan and Curtarolo's (``FCC``, ``RHL1``, ``TRI1a``, ...), ASE's
    (``HEX2D``, ``SQR``, ``RECT``, ``CRECT``, ``OBL``) or ``LINE`` for a
    wire. ``space_group`` is the group of the typed cell the path was read
    on, the layer's primitive cell for a slab, e.g. ``P-6m2 (187)``.
    ``primitive_cells`` is the number of primitive cells the written cell
    holds; above 1 the bands or phonon branches are folded. ``cell`` is the
    written cell."""

    branches: tuple[PathBranch, ...]
    k_path_distance: float
    n_kpoints: int
    convention: PathConvention
    lattice_type: str
    space_group: str
    primitive_cells: int
    cell: Structure
    warnings: tuple[Warning, ...] = ()


class KPathHumanInput(HumanInput):
    k_path_distance: float | None = Field(default=None, ge=1e-3)
    """The largest spacing between neighbouring path points, in 1/Å with 2π
    included. The bound keeps every step above bands.x's test for two equal
    points, 1e-4 2π/alat (``PP/src/bands.f90:537-541``), for any alat
    above 0.63 Å."""


@dataclass(frozen=True, slots=True)
class _Reading:
    """A path as a cell's symmetry gives it, before merging and counting:
    each label's crystal coordinates in the written cell's reciprocal basis,
    the table's continuous pieces as labels, and the record's description
    of the table and the cell."""

    points: dict[str, np.ndarray]
    sub_paths: tuple[tuple[str, ...], ...]
    convention: PathConvention
    lattice_type: str
    space_group: str
    primitive_cells: int
    warnings: tuple[Warning, ...] = ()


@dataclass(frozen=True, slots=True)
class _PrimitiveLayer:
    """A layer's primitive cell, as spglib takes a cell: ``lattice`` keeps
    the normal vacuum vector, ``basis`` holds its in-plane rows in fractional
    coordinates of the unstacked cell's in-plane vectors, and ``cells`` is
    the number of primitive cells the unstacked cell holds."""

    lattice: np.ndarray
    positions: np.ndarray
    types: list[int]
    basis: np.ndarray
    cells: int


def k_path(
    cell: FieldState[MagneticCell], human: KPathHumanInput | None = None
) -> FieldState[KPathDecision]:
    """The band path of the written ``cell`` (module docstring), its points
    spaced by the human ``k_path_distance``, else
    ``DEFAULT_K_PATH_DISTANCE``. ``Blocked`` when ``cell`` is not resolved or
    is a molecule or cluster in a box (vacuum along every lattice vector)."""
    human = human or KPathHumanInput()
    if not cell.ok:
        return Blocked(by=blocked_by(cell))
    written = cell.value.structure
    vacuum = tuple(LATTICE_AXES.index(axis) for axis in vacuum_axes(written))
    if len(vacuum) == 3:
        return Blocked(by=_BOX)
    distance = (
        DEFAULT_K_PATH_DISTANCE
        if human.k_path_distance is None
        else human.k_path_distance
    )
    lattice = _unstacked(written.lattice.matrix, vacuum)
    reading = _reading(written, vacuum, lattice)
    branches = _counted(reading, _reciprocal(lattice), distance)
    decision = KPathDecision(
        branches=branches,
        k_path_distance=distance,
        n_kpoints=sum(sum(branch.steps) + 1 for branch in branches),
        convention=reading.convention,
        lattice_type=reading.lattice_type,
        space_group=reading.space_group,
        primitive_cells=reading.primitive_cells,
        cell=written,
        warnings=_notices(reading, cell.value),
    )
    return Resolved(decision, _provenance(human, reading.convention))


def _reading(cell: Structure, vacuum: tuple[int, ...], lattice: np.ndarray) -> _Reading:
    """The path of ``cell`` by its vacuum axes (indices into ``LATTICE_AXES``):
    a wire's for two, a layer's for one, the bulk path for none. ``lattice``
    is the written lattice after ``_unstacked``."""
    if len(vacuum) == 2:
        return _wire(cell, vacuum)
    if vacuum:
        return _layer(cell, vacuum[0], lattice)
    return _bulk(cell)


def _types(cell: Structure) -> list[int]:
    """One integer per site, numbered from 1 by first appearance of the
    site's label: the species pw.x is given."""
    index: dict[str, int] = {}
    return [index.setdefault(site.label, len(index) + 1) for site in cell]


def _dataset(
    lattice: np.ndarray, positions: np.ndarray, types: Sequence[int]
) -> spglib.SpglibDataset:
    """spglib's symmetry dataset of the cell (rows of ``lattice``, fractional
    ``positions``) at ``FRAME_TOLERANCE``."""
    return spglib.get_symmetry_dataset(
        (lattice, positions, types), symprec=FRAME_TOLERANCE
    )


def _space_group(dataset: spglib.SpglibDataset) -> str:
    return f"{dataset.international} ({dataset.number})"


def _pure_translations(dataset: spglib.SpglibDataset) -> np.ndarray:
    """The translations, one row each, of the operations whose rotation is
    the identity, the identity itself included."""
    identity = np.all(dataset.rotations == np.eye(3, dtype=int), axis=(1, 2))
    return dataset.translations[identity]


def _reciprocal(lattice: np.ndarray) -> np.ndarray:
    """The reciprocal vectors of ``lattice`` (rows), 2π included."""
    return 2 * np.pi * np.linalg.inv(lattice).T


def _unstacked(lattice: np.ndarray, vacuum: tuple[int, ...]) -> np.ndarray:
    """``lattice`` (rows) with each vacuum vector replaced by its component
    normal to the periodic vectors: a slab's along the sheet's normal, a
    wire's across the wire. A lattice without vacuum is returned as it is."""
    unstacked = lattice.copy()
    periodic = lattice[[index for index in range(3) if index not in vacuum]]
    projector = periodic.T @ np.linalg.solve(periodic @ periodic.T, periodic)
    for index in vacuum:
        unstacked[index] = lattice[index] - lattice[index] @ projector
    return unstacked


# ----------------------------------------------------------------------- bulk


def _bulk(cell: Structure) -> _Reading:
    """Setyawan and Curtarolo's path for ``cell`` (module docstring). The
    typed copy has one stand-in element per species and no site properties,
    so pymatgen's handling of magnetic moments cannot interfere."""
    types = _types(cell)
    typed = Structure(
        cell.lattice, [_TYPE_ELEMENTS[kind - 1] for kind in types], cell.frac_coords
    )
    with warnings.catch_warnings():
        warnings.filterwarnings(
            "ignore", message=_NOT_STANDARD_PRIMITIVE, category=UserWarning
        )
        setyawan = KPathSetyawanCurtarolo(
            typed, symprec=FRAME_TOLERANCE, angle_tolerance=-1
        )
    dataset = _dataset(cell.lattice.matrix, cell.frac_coords, types)
    table = _table(setyawan, dataset)
    correspondence = _correspondence(typed, setyawan.prim)
    general = setyawan.name == "RHL1" and dataset.number in _GENERAL_POINT_GROUPS
    return _Reading(
        points={
            _ascii(label): np.asarray(point, dtype=float) @ correspondence.T
            for label, point in table["kpoints"].items()
        },
        sub_paths=tuple(
            tuple(_ascii(label) for label in sub_path) for sub_path in table["path"]
        ),
        convention="setyawan_curtarolo",
        lattice_type=setyawan.name,
        space_group=_space_group(dataset),
        primitive_cells=round(abs(np.linalg.det(correspondence))),
        warnings=(NON_SPECIAL_VERTICES,) if general else (),
    )


def _table(
    setyawan: KPathSetyawanCurtarolo, dataset: spglib.SpglibDataset
) -> dict[str, Any]:
    """pymatgen's path for the typed cell, as ``.kpath`` holds it, except
    where pymatgen picks the table or the cell by exact comparisons: a
    triclinic cell (space group 1 or 2) gets ``_triclinic``'s table and a
    primitive monoclinic cell ``_monoclinic``'s. Any other cell without a
    path is a fault, and raises ``RuntimeError``."""
    if dataset.number <= _LAST_TRICLINIC_GROUP:
        return _triclinic(setyawan)
    if setyawan.kpath is None:
        raise RuntimeError(
            "pymatgen gives no Setyawan-Curtarolo path for the written "
            f"cell's space group {_space_group(dataset)}"
        )
    if setyawan.name == "MCL":
        return _monoclinic(setyawan)
    return setyawan.kpath


def _triclinic(setyawan: KPathSetyawanCurtarolo) -> dict[str, Any]:
    """Setyawan and Curtarolo's TRI1b table when every reciprocal angle of
    the standard primitive cell is acute, else their TRI1a table: all
    obtuse, or one or more right to within ``_RIGHT_ANGLE``, where their
    conditions do not settle the table and pymatgen gives none or picks one
    by rounding. Both tables run from Gamma to the seven
    time-reversal-invariant points, under different labels; each point is
    moved to its shortest equivalent in the reciprocal lattice of the
    standard primitive cell (module docstring)."""
    acute = all(angle < 90 - _RIGHT_ANGLE for angle in setyawan.prim_rec.angles)
    table = setyawan.trib() if acute else setyawan.tria()
    reciprocal = setyawan.prim_rec.matrix
    return {
        "kpoints": {
            label: _shortest(np.asarray(point, dtype=float), reciprocal)
            for label, point in table["kpoints"].items()
        },
        "path": table["path"],
    }


def _monoclinic(setyawan: KPathSetyawanCurtarolo) -> dict[str, Any]:
    """Setyawan and Curtarolo's MCL table, evaluated on the standard
    primitive cell P put in their setting by the first signed axis
    permutation T of ``_MCL_SETTINGS`` that does (``_in_mcl_setting``), its
    points carried back into P's reciprocal basis as k T. pymatgen keeps an
    axis order only where b < c, so when the two lattice vectors normal to
    the unique axis are equal in length -- a monoclinic crystal on a
    C-centred orthorhombic or hexagonal lattice -- it leaves P in another
    setting, and its own table then loses or misplaces the zone corners H
    and M and puts points outside the first zone."""
    lattice = setyawan.prim.lattice.matrix
    setting = next(
        setting
        for setting in _MCL_SETTINGS
        if _in_mcl_setting(Lattice(setting @ lattice))
    )
    _, b, c, alpha, _, _ = Lattice(setting @ lattice).parameters
    table = setyawan.mcl(b, c, alpha * math.pi / 180)
    return {
        "kpoints": {
            label: np.asarray(point, dtype=float) @ setting
            for label, point in table["kpoints"].items()
        },
        "path": table["path"],
    }


def _in_mcl_setting(lattice: Lattice) -> bool:
    """Whether ``lattice`` is in Setyawan and Curtarolo's MCL setting, to
    rounding: beta and gamma right, alpha at most 90 degrees, and b no
    longer than c."""
    _, b, c, alpha, beta, gamma = lattice.parameters
    right = abs(beta - 90) < _RIGHT_ANGLE and abs(gamma - 90) < _RIGHT_ANGLE
    return right and alpha < 90 + _RIGHT_ANGLE and (b < c or math.isclose(b, c))


def _shortest(point: np.ndarray, reciprocal: np.ndarray) -> np.ndarray:
    """``point``, in fractions of the ``reciprocal`` rows, moved by the
    reciprocal lattice vector with components -1, 0 or 1 that leaves it
    shortest -- enough for pymatgen's reduced standard primitive cell -- or
    left where it is when no move shortens it by more than rounding."""
    candidates = point - _SHIFTS
    lengths = np.linalg.norm(candidates @ reciprocal, axis=1)
    return candidates[np.flatnonzero(lengths <= lengths.min() * (1 + 1e-9))[0]]


def _ascii(label: str) -> str:
    """pymatgen's LaTeX label in ASCII: ``\\Gamma`` -> ``Gamma``."""
    return label.replace("\\", "")


def _correspondence(typed: Structure, primitive: Structure) -> np.ndarray:
    """N, the integer matrix whose rows are ``typed``'s lattice vectors in
    ``primitive``'s basis: of ``primitive``'s lattice mappings onto
    ``typed``'s, the first that ``_maps`` accepts with a proper rotation,
    else the first accepted. ``primitive`` is a primitive cell of ``typed``,
    so a cell none maps is a fault, and raises ``RuntimeError``."""
    improper = None
    for _, rotation, scale in primitive.lattice.find_all_mappings(
        typed.lattice, ltol=1e-4, atol=0.01
    ):
        matrix = np.rint(scale).astype(int)
        if not _maps(typed, primitive, matrix):
            continue
        if np.linalg.det(rotation) > 0:
            return matrix
        if improper is None:
            improper = matrix
    if improper is None:
        raise RuntimeError(
            "no integer lattice correspondence maps the written cell onto "
            "its standard primitive cell"
        )
    return improper


def _maps(typed: Structure, primitive: Structure, matrix: np.ndarray) -> bool:
    """Whether ``matrix`` takes ``typed`` onto ``primitive``: the metrics
    agree to 1e-3 relative, |det| copies of ``primitive`` hold ``typed``'s
    atoms, and every site of ``typed``, taken into ``primitive``'s basis and
    moved by one common translation, lands within ``_SITE_TOLERANCE`` of a
    site of its type. The translations tried send the first site onto each
    site of its type."""
    metric = typed.lattice.matrix @ typed.lattice.matrix.T
    image = matrix @ primitive.lattice.matrix
    if np.abs(metric - image @ image.T).max() > 1e-3 * np.abs(metric).max():
        return False
    if round(abs(np.linalg.det(matrix))) * len(primitive) != len(typed):
        return False
    positions = typed.frac_coords @ matrix
    types = np.array([site.specie.Z for site in typed])
    targets = np.array([site.specie.Z for site in primitive])
    return any(
        _lands(
            positions + primitive.frac_coords[start] - positions[0],
            types,
            primitive,
            targets,
        )
        for start in np.flatnonzero(targets == types[0])
    )


def _lands(
    positions: np.ndarray, types: np.ndarray, primitive: Structure, targets: np.ndarray
) -> bool:
    """Whether every one of ``positions`` (fractional in ``primitive``'s
    basis) lies within ``_SITE_TOLERANCE`` of a site of ``primitive`` of its
    type; ``types`` and ``targets`` are the dummy elements' atomic numbers."""
    offsets = primitive.frac_coords[None, :, :] - positions[:, None, :]
    offsets -= np.rint(offsets)
    distances = np.linalg.norm(offsets @ primitive.lattice.matrix, axis=2)
    distances[types[:, None] != targets[None, :]] = np.inf
    return bool(distances.min(axis=1).max() <= _SITE_TOLERANCE)


# ---------------------------------------------------------------------- layer


def _layer(cell: Structure, axis: int, lattice: np.ndarray) -> _Reading:
    """ASE's 2D path for the layer of ``cell``, whose vacuum lies along
    lattice vector ``axis``; ``lattice`` is ``cell``'s with that vector
    along the sheet's normal (module docstring)."""
    plane = [index for index in range(3) if index != axis]
    cartesian = _contiguous(cell, axis) @ cell.lattice.matrix
    layer = _primitive_layer(
        lattice, cartesian @ np.linalg.inv(lattice), _types(cell), plane
    )
    dataset = _dataset(layer.lattice, layer.positions, layer.types)
    blocks = [rotation[np.ix_(plane, plane)] for rotation in dataset.rotations]
    vectors = layer.lattice[plane]
    name, standard = _standard_2d(blocks, vectors)
    points = _ase_points(name, standard @ vectors)
    # Standard rows in the unstacked cell's in-plane fractional coordinates
    # are standard @ basis; a k point's coordinates go by its inverse
    # transpose.
    to_cell = np.linalg.inv(standard @ layer.basis).T
    return _Reading(
        points={
            label: _in_plane(point @ to_cell, plane) for label, point in points.items()
        },
        sub_paths=(_ASE_PATHS[name],),
        convention="bravais_2d",
        lattice_type=name,
        space_group=_space_group(dataset),
        primitive_cells=layer.cells,
    )


def _contiguous(cell: Structure, axis: int) -> np.ndarray:
    """``cell``'s fractional coordinates with each one along ``axis`` wrapped
    into (c, c + 1), c the middle of the widest vacuum along it, so the layer
    lies in one piece: ``framed_cell`` moves a slab's origin only to gain
    symmetry, so a written slab can straddle the cell boundary."""
    centre = slab_geometry(cell).vacuum_center
    positions = cell.frac_coords.copy()
    positions[:, axis] = centre + np.mod(positions[:, axis] - centre, 1.0)
    return positions


def _primitive_layer(
    lattice: np.ndarray, positions: np.ndarray, types: list[int], plane: list[int]
) -> _PrimitiveLayer:
    """The primitive cell of the typed layer (``lattice`` unstacked,
    ``positions`` fractional in it). Its ``count`` pure translations, the
    identity included, have in-plane components that are multiples of
    1/count, so count times them and count times the in-plane unit vectors
    span count times the primitive 2D lattice. One site is kept per orbit of
    the translations (spglib's ``mapping_to_primitive``)."""
    dataset = _dataset(lattice, positions, types)
    translations = _pure_translations(dataset)
    count = len(translations)
    generators = np.vstack(
        [
            count * np.eye(2, dtype=int),
            np.rint(count * translations[:, plane]).astype(int),
        ]
    )
    basis = _lattice_basis(generators) / count
    primitive = lattice.copy()
    primitive[plane] = basis @ lattice[plane]
    kept = np.sort(np.unique(dataset.mapping_to_primitive, return_index=True)[1])
    return _PrimitiveLayer(
        lattice=primitive,
        positions=positions[kept] @ lattice @ np.linalg.inv(primitive),
        types=[types[index] for index in kept],
        basis=basis,
        cells=round(1 / abs(np.linalg.det(basis))),
    )


def _lattice_basis(generators: np.ndarray) -> np.ndarray:
    """An integer basis of the 2D lattice the integer rows ``generators``
    span: Euclid's algorithm on their first components leaves one row
    holding their gcd there and the others 0 there, whose second components'
    gcd gives the second basis row."""
    pivot = np.zeros(2, dtype=int)
    seconds = []
    for row in generators:
        pivot, remainder = _euclid(pivot, row)
        seconds.append(int(remainder[1]))
    return np.array([pivot, [0, math.gcd(*seconds)]])


def _euclid(first: np.ndarray, second: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """``first`` and ``second`` combined by unimodular steps into a row whose
    first component is the gcd of theirs and a row whose first component
    is 0."""
    while second[0] != 0:
        first, second = second, first - (first[0] // second[0]) * second
    return first, second


def _bravais_2d(blocks: list[np.ndarray]) -> str:
    """A layer's 2D Bravais system from the in-plane blocks of its
    operations: a proper rotation of order 3 or 6 (determinant 1, trace
    +-1) makes it hexagonal, else one of order 4 (trace 0) square, else a
    reflection (determinant -1: a vertical mirror or an in-plane 2-fold
    axis) rectangular, else it is oblique."""
    kinds = {(round(np.linalg.det(block)), int(np.trace(block))) for block in blocks}
    if kinds & {(1, 1), (1, -1)}:
        return "hexagonal"
    if (1, 0) in kinds:
        return "square"
    if any(determinant == -1 for determinant, _ in kinds):
        return "rectangular"
    return "oblique"


def _standard_2d(
    blocks: list[np.ndarray], vectors: np.ndarray
) -> tuple[str, np.ndarray]:
    """ASE's lattice name for the layer and the integer rows of its standard
    cell in the basis of the primitive in-plane ``vectors``: from the
    reduced basis (s1, s2), the pair at 120 degrees for HEX2D, (s1, s2) for
    SQR, and for OBL (s1, +-s2) with an angle of at most 90 degrees; RECT
    and CRECT from a reflection (``_rectangular``)."""
    system = _bravais_2d(blocks)
    if system == "rectangular":
        return _rectangular(blocks, vectors)
    rows = _reduced(vectors)
    first, second = rows @ vectors
    if system == "hexagonal":
        turned = first @ second > 0
        return "HEX2D", np.array([rows[0], rows[1] - rows[0]]) if turned else rows
    if system == "square":
        return "SQR", rows
    return "OBL", np.array([rows[0], -rows[1]]) if first @ second < 0 else rows


def _reduced(vectors: np.ndarray) -> np.ndarray:
    """The unimodular integer rows U with ``U @ vectors`` Lagrange-Gauss
    reduced: the first no longer than the second, and the projection of the
    second on the first at most half the first, to rounding."""
    rows = np.eye(2, dtype=int)
    while True:
        first, second = rows @ vectors
        if second @ second < (1 - 1e-12) * (first @ first):
            rows = rows[[1, 0]]
            continue
        ratio = float(first @ second / (first @ first))
        if abs(ratio) <= 0.5 + 1e-9:
            return rows
        rows[1] -= round(ratio) * rows[0]


def _rectangular(
    blocks: list[np.ndarray], vectors: np.ndarray
) -> tuple[str, np.ndarray]:
    """RECT or CRECT and the standard rows. The shortest lattice vectors
    along a reflection's mirror line and normal to it span the lattice
    (RECT, the shorter first, as ASE has a < b) or a sublattice of index 2
    (CRECT, whose primitive rows are (L + S)/2 and (L - S)/2, L the longer of
    the two and S the shorter, at an angle below 90 degrees)."""
    reflection = next(block for block in blocks if round(np.linalg.det(block)) == -1)
    rows = np.array([_line_vector(reflection, 1), _line_vector(reflection, -1)])
    order = np.argsort(np.linalg.norm(rows @ vectors, axis=1), kind="stable")
    short, long = rows[order]
    if abs(round(np.linalg.det(rows))) == 1:
        return "RECT", np.array([short, long])
    return "CRECT", np.array([(long + short) // 2, (long - short) // 2])


def _line_vector(reflection: np.ndarray, sign: int) -> np.ndarray:
    """The shortest lattice vector that the in-plane ``reflection`` (acting
    on integer column vectors) maps to ``sign`` times itself: along its
    mirror line for +1, normal to it for -1. For any lattice vector n,
    n + sign R n is one."""
    candidates = (unit + sign * (reflection @ unit) for unit in np.eye(2, dtype=int))
    vector = next(candidate for candidate in candidates if candidate.any())
    return vector // math.gcd(*(int(value) for value in vector))


def _ase_points(name: str, vectors: np.ndarray) -> dict[str, np.ndarray]:
    """ASE's special points of the 2D lattice ``name`` on the standard cell
    ``vectors`` (``ase.lattice``), in fractions of its reciprocal basis."""
    a, b = (float(length) for length in np.linalg.norm(vectors, axis=1))
    alpha = math.acos(float(np.clip(vectors[0] @ vectors[1] / (a * b), -1.0, 1.0)))
    if name == "HEX2D":
        points = {"Gamma": (0, 0), "M": (0.5, 0), "K": (1 / 3, 1 / 3)}
    elif name == "SQR":
        points = {"Gamma": (0, 0), "X": (0, 0.5), "M": (0.5, 0.5)}
    elif name == "RECT":
        points = {"Gamma": (0, 0), "X": (0.5, 0), "S": (0.5, 0.5), "Y": (0, 0.5)}
    elif name == "CRECT":
        eta = math.sin(alpha / 2) ** 2 / math.sin(alpha) ** 2
        xi = eta * math.cos(alpha)
        points = {
            "Gamma": (0, 0),
            "X": (eta, -eta),
            "A_1": (0.5 + xi, 0.5 - xi),
            "Y": (0.5, 0.5),
        }
    else:
        eta = (1 - a * math.cos(alpha) / b) / (2 * math.sin(alpha) ** 2)
        nu = 0.5 - eta * b * math.cos(alpha) / a
        points = {
            "Gamma": (0, 0),
            "Y": (0, 0.5),
            "H": (eta, 1 - nu),
            "C": (0.5, 0.5),
            "H_1": (1 - eta, nu),
            "X": (0.5, 0),
        }
    return {label: np.array(point, dtype=float) for label, point in points.items()}


def _in_plane(point: np.ndarray, plane: list[int]) -> np.ndarray:
    """The 3D crystal coordinates of an in-plane ``point``, 0 along the
    vacuum axis."""
    k = np.zeros(3)
    k[plane] = point
    return k


# ----------------------------------------------------------------------- wire


def _wire(cell: Structure, vacuum: tuple[int, ...]) -> _Reading:
    """Gamma to Z along the wire of ``cell`` (module docstring). The periods
    along it are the pure translations of the typed cell with no component
    across the vacuum."""
    (axis,) = (index for index in range(3) if index not in vacuum)
    dataset = _dataset(cell.lattice.matrix, cell.frac_coords, _types(cell))
    across = _pure_translations(dataset)[:, list(vacuum)]
    periods = int(
        np.all(np.abs(across - np.rint(across)) < _TRANSLATION_TOLERANCE, axis=1).sum()
    )
    z = np.zeros(3)
    z[axis] = periods / 2
    return _Reading(
        points={"Gamma": np.zeros(3), "Z": z},
        sub_paths=(("Gamma", "Z"),),
        convention="wire",
        lattice_type="LINE",
        space_group=_space_group(dataset),
        primitive_cells=periods,
    )


# ---------------------------------------------------- merging and counting


def _counted(
    reading: _Reading, reciprocal: np.ndarray, distance: float
) -> tuple[PathBranch, ...]:
    """The merged branches of ``reading`` with their steps (module
    docstring), lengths measured with the ``reciprocal`` vectors."""
    points = reading.points

    def same(first: str, second: str) -> bool:
        separation = (points[first] - points[second]) @ reciprocal
        return bool(np.linalg.norm(separation) < _SAME_POINT)

    return tuple(
        PathBranch(
            vertices=tuple(
                PathVertex(label, _recorded(points[label])) for label in labels
            ),
            steps=tuple(
                _steps(points[end] - points[start], reciprocal, distance)
                for start, end in itertools.pairwise(labels)
            ),
        )
        for labels in _first_labels(_merged(reading.sub_paths, same), same)
    )


def _merged(
    sub_paths: tuple[tuple[str, ...], ...], same: Callable[[str, str], bool]
) -> list[list[str]]:
    """The branches of ``sub_paths`` as labels (module docstring): a vertex
    at the point before it is dropped; a vertex at the point two places
    back, and the first vertex of each sub-path, open a new branch
    (``_open``); a branch left with one vertex is dropped."""
    branches: list[list[str]] = []
    for sub_path in sub_paths:
        for index, label in enumerate(sub_path):
            current = branches[-1] if branches else []
            if current and same(current[-1], label):
                continue
            turning = len(current) > 1 and same(current[-2], label)
            if index and not turning:
                current.append(label)
            else:
                _open(branches, label, same)
    return [branch for branch in branches if len(branch) > 1]


def _open(
    branches: list[list[str]], label: str, same: Callable[[str, str], bool]
) -> None:
    """Start a branch at ``label`` after dropping a last branch of one
    vertex -- unless the last branch left ends at the point of ``label``,
    which then continues it, so that no two consecutive points coincide
    across a branch boundary either."""
    if branches and len(branches[-1]) < 2:
        branches.pop()
    if not (branches and same(branches[-1][-1], label)):
        branches.append([label])


def _first_labels(
    branches: list[list[str]], same: Callable[[str, str], bool]
) -> list[list[str]]:
    """``branches`` with each label replaced by the first label, in path
    order, at the same point."""
    seen: list[str] = []

    def first(label: str) -> str:
        match = next((name for name in seen if same(name, label)), None)
        if match is None:
            seen.append(label)
            return label
        return match

    return [[first(label) for label in branch] for branch in branches]


def _steps(separation: np.ndarray, reciprocal: np.ndarray, distance: float) -> int:
    """The equal steps a segment of crystal-coordinate ``separation`` takes:
    the fewest, at least one, no longer than ``distance``."""
    length = float(np.linalg.norm(separation @ reciprocal))
    return max(1, math.ceil(round(length / distance, 5)))


def _recorded(k: np.ndarray) -> tuple[float, float, float]:
    """``k`` as plain floats, a component within ``_ZERO`` of 0 recorded as
    0 (rotating the table into the written basis leaves 1e-17 residues)."""
    x, y, z = (0.0 if abs(value) < _ZERO else float(value) for value in k)
    return x, y, z


# -------------------------------------------------------- notices, provenance


def _notices(reading: _Reading, cell: MagneticCell) -> tuple[Warning, ...]:
    """The reading's own notices, then ``k_path.folded_bands`` and
    ``k_path.magnetic_noncollinear_symmetry`` where they apply (module
    docstring)."""
    notices = list(reading.warnings)
    if reading.primitive_cells > 1:
        notices.append(_folded(reading.primitive_cells))
    if cell.spin_polarized and cell.spin_orbit_enabled:
        notices.append(MAGNETIC_NONCOLLINEAR_SYMMETRY)
    return tuple(notices)


def _folded(cells: int) -> Warning:
    """``k_path.folded_bands`` for a written cell of ``cells`` primitive
    cells."""
    return FOLDED_BANDS.model_copy(
        update={
            "message": (
                f"the written cell holds {cells} primitive cells (a conventional "
                "cell or a supercell), so the high-symmetry path, taken from the "
                "primitive cell, gives folded bands or phonon branches: at each "
                f"point those of {cells} points of the primitive cell's Brillouin "
                "zone appear together. Upload the primitive cell to unfold them."
            )
        }
    )


def _provenance(human: KPathHumanInput, convention: PathConvention) -> Provenance:
    """``k_path_distance`` reads ``human`` when the request set it, else
    ``heuristic`` with the protocol it comes from; the path follows the
    written cell (``magnetic``) and cites its table."""
    return Provenance.from_field_sources(
        field_sources_from(human, None, fields=["k_path_distance"]),
        source_note=None if human.k_path_distance is not None else _DEFAULT_NOTE,
        derived_from=("magnetic",),
        citations=_CITATIONS[convention],
    )
