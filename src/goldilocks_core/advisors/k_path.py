"""k_path: the band-structure path of the written cell (#118).

The path is read from the cell pw.x is given: the simulated cell
``magnetic_cell`` decides and ``framed_cell`` writes
(``MagneticCell.structure``). Each site is typed by its species label, the
``ATOMIC_SPECIES`` type the writer gives it, so sublattices of opposite spin
(``Ni1``/``Ni2``) stay apart and an antiferromagnetic run gets the path of
its magnetic cell. Symmetry is searched at ``pw_symmetry.FRAME_TOLERANCE``,
the tolerance that cell was idealized to. The vertices are crystal
coordinates of the written cell's reciprocal vectors, as ``K_POINTS
crystal_b`` takes them, so a conventional cell or a supercell gets the path
of its primitive cell and folded bands: ``KPathDecision.primitive_cells``
counts the primitive cells the written cell holds.

The vacuum of the written cell (``analysis.geometry.vacuum_axes``) decides
the kind of path:

- **Bulk.** Setyawan and Curtarolo's path for the lattice type
  (Comput. Mater. Sci. 49, 299 (2010)), as pymatgen's
  ``KPathSetyawanCurtarolo`` gives it in the reciprocal basis of its
  standard primitive cell P. The integer matrix N whose rows are the
  written lattice vectors in P's basis carries a vertex over as
  k = k_P N^T: the rotation between the two frames is absorbed in N, and an
  origin shift does not act on k. N comes from P's lattice mappings onto
  the written lattice and is accepted only when the metrics agree, |det N|
  copies of P hold the written cell's atoms, and every written site, taken
  into P's basis and moved by one common translation, lands on a site of
  its own type (``_correspondence``); the first accepted one with a proper
  rotation is kept. Two accepted matrices differ by an operation of the
  crystal, so their vertices are equivalent. pymatgen picks the table and
  P by comparing angles and lengths exactly, which ``_table`` redoes to
  rounding in two cases. A triclinic path runs from Gamma to each of the
  seven time-reversal-invariant points, by Setyawan and Curtarolo's TRI1b
  table when every reciprocal angle of P is acute and by their TRI1a table
  otherwise: where a reciprocal angle is right, pymatgen gives no path or
  picks a table by rounding at 1e-14 degrees, which differs between
  orientations of one cell. Each point of a triclinic table is moved by a
  reciprocal lattice vector of P to its shortest equivalent: the tables'
  coordinates are those of Setyawan and
  Curtarolo's reduced reciprocal cell, which pymatgen's P need not be, so
  they can lie outside the first zone (TRI1b's N often does, and TRI1a's
  points do once a reciprocal angle is acute), while a
  time-reversal-invariant point k at its shortest is as far from Gamma as
  from 2k, so on the zone boundary, and every segment from Gamma stays in
  the first zone. And a primitive monoclinic cell whose two lattice
  vectors normal to the unique axis are equal in length, which pymatgen
  leaves out of Setyawan and Curtarolo's MCL setting, is put in it before
  their table is read (``_monoclinic``). Any other cell pymatgen gives no
  path for is a fault.
- **Slab** (one vacuum axis). The layer is made contiguous along its vacuum
  axis about the middle of the vacuum, and the vacuum vector is replaced by
  its component along the sheet's normal, atoms keeping their Cartesian
  positions (``_unstacked``): a tilted c would lower the cell's 3D group,
  and a sheet straddling the cell boundary would be sheared. The layer's
  primitive 2D lattice is generated by the in-plane vectors and the pure
  translations spglib finds; spglib lists only the operations that map the
  given lattice onto itself, so in a supercell a honeycomb layer would pass
  for centred rectangular. The 2D Bravais system is read from the in-plane
  action of the primitive layer's operations (``_bravais_2d``); time
  reversal adds the 2D half turn, which changes no class. A monoclinic
  layer whose unique axis lies in the sheet (1T'-WTe2, or SlabGenerator's
  Cu(211) and TiO2(101) slabs) is rectangular. The path is ASE's for that
  system, as ``ase.lattice`` defines HEX2D, SQR, RECT, CRECT and OBL and
  C2DB uses them (Larsen et al., J. Phys.: Condens. Matter 29, 273002
  (2017)), on its standard cell, with every vertex at 0 along the vacuum
  axis; the component along the normal does not change a slab's bands.
- **Wire** (two vacuum axes). Gamma to Z, Z being half the reciprocal
  vector along the wire times the number of periods the cell holds along
  it.
- **Molecule or cluster in a box** (three). No band structure, so the path
  is ``Blocked`` with a reason naming the tasks that apply.

**Merging.** Vertices of a table can coincide for a particular metric
(Setyawan and Curtarolo's X_1 and Y in a C-centred orthorhombic cell with
a = b; ASE's H, C and H_1 on an oblique layer with a right angle), and two
equal consecutive points make bands.x skip its plot file while still
reporting success (QE 7.3 ``PP/src/bands.f90:537-541``). So a vertex at the
point before it is dropped; a vertex at the point two places back -- a walk
back along the segment just taken -- ends the branch at the turning vertex,
and a new branch starts at that vertex; a branch that starts where the
previous one ends continues it; a branch left with one vertex is dropped;
and every vertex at a point takes the first label used there (``_merged``,
``_first_labels``). The path thus never repeats a point, as bands.x needs;
the phonon tasks' dispersion step, which follows it too, repeats Gamma
where matdyn.x needs that, outside ``k_path()`` (``advisors/phonon.py``'s
``dispersion_path``).

**Counts.** A segment takes ``ceil(length / k_path_distance)`` equal steps,
at least one, the quotient rounded to 5 decimals first as ``kmesh`` rounds
it, so no step is longer than the distance. Lengths are measured with the
reciprocal vectors of the written lattice after ``_unstacked``, so a slab's
segments are measured in its plane and a wire's along it. ``n_kpoints`` is
then the number of points pw.x runs per spin channel on the band task's
bands step (``Modules/read_cards.f90:824-827``).

**Notices.** ``k_path.folded_bands`` when the written cell holds more than
one primitive cell, whose bands or phonon branches the path folds.
``k_path.magnetic_noncollinear_symmetry`` for a spin-polarized run with
spin-orbit coupling: the typing ignores the moment directions, so segments
the path treats as equivalent may differ, and for the bands it assumes
E(k) = E(-k), which such a run can break.
``k_path.non_special_vertices`` for a bulk cell typed R3 or R-3 with the
RHL1 variant, where Setyawan and Curtarolo's B, B_1, P, P_1, Q and X are
general points. Both tables choose paths by lattice type: ASE's oblique
loop encloses about a third of the zone, and its corners H and H_1 are
general points too. Where the lattice is more symmetric than the crystal
(P1 or P-1 on an orthorhombic, monoclinic or hexagonal lattice, a
monoclinic crystal on an orthorhombic lattice or with two equal axes
normal to its unique axis), several settings of a table, or several
equally short equivalents of a vertex (``_shortest``), fit the lattice
alike, and the one taken follows the frame of the written cell: the labels
can move, and a segment can follow a line that the crystal's symmetry does
not relate to another frame's, while every vertex stays a special point on
the zone boundary.
"""

